import { assertLawRecord, type LawEventType, type LawKind, type LawRecord } from "./types";

type Seed = Omit<LawRecord, "id" | "kind"> & { id: string; kinds?: LawKind[] };

function expand(seed: Seed): LawRecord[] {
  const kinds = seed.kinds ?? ["civil"];
  return kinds.map((kind) => {
    const { kinds: _ignored, ...rest } = seed;
    return {
      ...rest,
      id: kinds.length === 1 ? seed.id : `${seed.id}-${kind}`,
      kind,
    };
  });
}

